package com.ko.footballupdater.controllers.views;

import com.ko.footballupdater.services.DraftReviewService;
import com.ko.footballupdater.services.FacebookApiService;
import com.ko.footballupdater.utils.MessageType;
import lombok.extern.slf4j.Slf4j;
import org.springframework.beans.factory.annotation.Autowired;
import org.springframework.stereotype.Controller;
import org.springframework.ui.Model;
import org.springframework.web.bind.annotation.GetMapping;
import org.springframework.web.bind.annotation.PathVariable;
import org.springframework.web.bind.annotation.PostMapping;
import org.springframework.web.bind.annotation.RequestMapping;
import org.springframework.web.bind.annotation.RequestParam;
import org.springframework.web.servlet.mvc.support.RedirectAttributes;

/**
 * Approval queue for drafts generated by the editor and caption agents.
 */
@Slf4j
@Controller
@RequestMapping(path = "/posts/review")
public class ReviewViewController {

    @Autowired
    private DraftReviewService draftReviewService;

    @Autowired
    private FacebookApiService facebookApiService;

    @GetMapping("")
    public String getReviewQueue(Model model) {
        model.addAttribute("drafts", draftReviewService.getPendingDrafts());
        model.addAttribute("rejectedDrafts", draftReviewService.getRejectedDrafts());
        model.addAttribute("facebookStatus", facebookApiService.prepareFacebookApiDto());
        return "review";
    }

    @PostMapping("/{postId}/approve")
    public String approve(@PathVariable("postId") Integer postId, @RequestParam(value = "caption", required = false) String caption,
                          RedirectAttributes redirectAttributes) {
        try {
            draftReviewService.approve(postId, caption);
            addMessage(redirectAttributes, "Post approved and uploaded to Instagram!", MessageType.SUCCESS);
        } catch (Exception ex) {
            log.atError().setMessage("Approving draft failed").setCause(ex).addKeyValue("postId", postId).log();
            addMessage(redirectAttributes, "Approving post failed - " + ex.getMessage(), MessageType.ERROR);
        }
        return "redirect:/posts/review";
    }

    @PostMapping("/{postId}/reject")
    public String reject(@PathVariable("postId") Integer postId, RedirectAttributes redirectAttributes) {
        try {
            draftReviewService.reject(postId);
            addMessage(redirectAttributes, "Post rejected", MessageType.SUCCESS);
        } catch (Exception ex) {
            log.atError().setMessage("Rejecting draft failed").setCause(ex).addKeyValue("postId", postId).log();
            addMessage(redirectAttributes, "Rejecting post failed - " + ex.getMessage(), MessageType.ERROR);
        }
        return "redirect:/posts/review";
    }

    @PostMapping("/{postId}/restore")
    public String restore(@PathVariable("postId") Integer postId, RedirectAttributes redirectAttributes) {
        try {
            draftReviewService.restore(postId);
            addMessage(redirectAttributes, "Post moved back to review", MessageType.SUCCESS);
        } catch (Exception ex) {
            log.atError().setMessage("Restoring draft failed").setCause(ex).addKeyValue("postId", postId).log();
            addMessage(redirectAttributes, "Restoring post failed - " + ex.getMessage(), MessageType.ERROR);
        }
        return "redirect:/posts/review";
    }

    private void addMessage(RedirectAttributes redirectAttributes, String message, MessageType messageType) {
        redirectAttributes.addFlashAttribute("message", message);
        redirectAttributes.addFlashAttribute("messageType", messageType.getType());
    }
}
